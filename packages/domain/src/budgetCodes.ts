/** ชื่อสำหรับเทียบ: ตัดคำนำ "โครงการ/กิจกรรม/ผลผลิต", ช่องว่าง, เครื่องหมาย */
export function codeKey(name: string): string {
  return normalizeKey(String(name).replace(/^\s*(\d+(\.\d+)*\s*)?(โครงการ|กิจกรรม(ย่อย)?|ผลผลิต)\s*/, ''));
}

export interface PlanChainNode { kind: string; name: string }

/** หมวดงบจากชื่อหัวข้อ "+ งบ…" ในแผน */
export function sectionOfChain(chain: ReadonlyArray<PlanChainNode>): BudgetCodeSection {
  const bt = chain.filter((n) => n.kind === 'BUDGET_TYPE').map((n) => n.name).join(' ');
  if (/อุดหนุน/.test(bt)) return 'SUBSIDY';
  if (/ลงทุน/.test(bt)) return 'INVESTMENT';
  if (/รายจ่ายอื่น/.test(bt)) return 'OTHER';
  return 'REGULAR';
}

export interface BudgetCodeMatch {
  budgetCode: string;
  mainActivityCode: string;
  section: BudgetCodeSection;
  activityName: string;
  itemName: string;
  /** อ้างอิงลำดับในเอกสารรหัส เช่น "งบรายจ่ายอื่น 1.2.1" */
  ref: string;
}

/**
 * หา "รหัสงบประมาณ" และ "รหัสกิจกรรมหลัก" ของรายการในแผน จากเส้นทาง แผนงาน → … → รายการย่อย
 * - หมวดงบดูจากหัวข้อ "+ งบรายจ่ายอื่น/งบเงินอุดหนุน/รายจ่ายลงทุน" (ไม่มี = งบประจำ)
 * - กิจกรรม: ชื่อในเส้นทางที่ตรงกับ "กิจกรรม" ในเอกสารรหัส (ระดับลึกสุดก่อน)
 * - หลายรายการค่าใช้จ่าย: เลือกที่ชื่อปรากฏในหัวข้อหมวดงบ; ไม่ชัดเจน = ไม่เดา (คืน null)
 */
export function matchBudgetCodes(entries: ReadonlyArray<BudgetCodeEntry>, fiscalYear: number, chain: ReadonlyArray<PlanChainNode>): BudgetCodeMatch | null {
  const fyRows = entries.filter((e) => Number(e.fiscalYear) === Number(fiscalYear));
  if (!fyRows.length) return null;
  const section = sectionOfChain(chain);
  const btText = codeKey(chain.filter((n) => n.kind === 'BUDGET_TYPE').map((n) => n.name).join(' '));
  const projKeys = new Set(chain.map((n) => codeKey(n.name)));
  const pick = (rows: BudgetCodeEntry[]): BudgetCodeEntry | null => {
    for (const n of [...chain].reverse()) {
      const k = codeKey(n.name);
      if (!k) continue;
      let hit = rows.filter((e) => codeKey(e.activityName) === k);
      if (!hit.length) continue;
      // ชื่อกิจกรรมซ้ำในหลายโครงการ → ใช้โครงการ/ผลผลิตในเส้นทางช่วยตัดสิน
      if (new Set(hit.map((e) => e.projectName)).size > 1) {
        const byProj = hit.filter((e) => projKeys.has(codeKey(e.projectName)));
        if (byProj.length) hit = byProj;
      }
      if (hit.length === 1) return hit[0];
      const byItem = hit.filter((e) => e.itemName && btText.includes(codeKey(e.itemName)));
      if (byItem.length === 1) return byItem[0];
      return new Set(hit.map((e) => e.budgetCode)).size === 1 ? hit[0] : null;
    }
    return null;
  };
  const e = pick(fyRows.filter((x) => x.section === section));
  if (!e) return null;
  return {
    budgetCode: e.budgetCode, mainActivityCode: e.mainActivityCode, section: e.section, activityName: e.activityName, itemName: e.itemName,
    ref: `${BUDGET_CODE_SECTION_NAME[e.section]} ${e.activityNo}`,
  };
}
